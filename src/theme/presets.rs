/// 内置主题预设枚举。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ThemePreset {
    /// LiteMiyu 薰衣草莫兰迪（MD3 柔和紫灰衍生·默认）
    MiyuLavender,
    /// LiteMiyu 经典暗夜紫蓝（Tokyo Night 基底）
    MiyuNight,
    /// Catppuccin Mocha（柔绒暖紫黑）
    CatppuccinMocha,
    /// Rosé Pine（月光玫瑰松）
    RosePine,
    /// Kanagawa Wave（浮世绘墨浪）
    KanagawaWave,
    /// Nord（北欧极夜蓝灰）
    Nord,
    /// Everforest Dark（森雾暖暗绿）
    EverforestDark,
    /// Gruvbox Dark（复古暖棕）
    GruvboxDark,
    /// Dracula（霓虹魅紫）
    Dracula,
    /// 鼠尾草森林暗色（MD3 柔和绿蓝衍生）
    MiyuForest,
    /// Catppuccin Latte（拿铁柔白浅色）
    CatppuccinLatte,
    /// 浅色护眼日间主题（Tokyo Night Day）
    MiyuDay,
    /// 暖调纸质护眼浅色主题（暖杏底色与墨色高对比）
    MiyuPaper,
    /// 透明继承宿主终端背景
    Terminal,
}

impl ThemePreset {
    /// 全部内置主题有序列表（用于 `/theme` 选择器展示）。
    pub const ALL: &'static [ThemePreset] = &[
        ThemePreset::MiyuLavender,
        ThemePreset::MiyuNight,
        ThemePreset::CatppuccinMocha,
        ThemePreset::RosePine,
        ThemePreset::KanagawaWave,
        ThemePreset::Nord,
        ThemePreset::EverforestDark,
        ThemePreset::GruvboxDark,
        ThemePreset::Dracula,
        ThemePreset::MiyuForest,
        ThemePreset::CatppuccinLatte,
        ThemePreset::MiyuDay,
        ThemePreset::MiyuPaper,
        ThemePreset::Terminal,
    ];

    /// 返回用于 CLI 参数、配置持久化与搜索匹配的稳定标识。
    pub fn id(self) -> &'static str {
        match self {
            Self::MiyuLavender => "miyu-lavender",
            Self::MiyuNight => "miyu-night",
            Self::CatppuccinMocha => "catppuccin-mocha",
            Self::RosePine => "rose-pine",
            Self::KanagawaWave => "kanagawa-wave",
            Self::Nord => "nord",
            Self::EverforestDark => "everforest-dark",
            Self::GruvboxDark => "gruvbox-dark",
            Self::Dracula => "dracula",
            Self::MiyuForest => "miyu-forest",
            Self::CatppuccinLatte => "catppuccin-latte",
            Self::MiyuDay => "miyu-day",
            Self::MiyuPaper => "miyu-paper",
            Self::Terminal => "terminal",
        }
    }

    /// 返回面向界面展示的中文说明标签。
    pub fn label(self) -> &'static str {
        match self {
            Self::MiyuLavender => "Miyu Lavender (莫兰迪紫蓝·默认)",
            Self::MiyuNight => "Miyu Night (Tokyo Night 深色)",
            Self::CatppuccinMocha => "Catppuccin Mocha (柔绒暖紫黑)",
            Self::RosePine => "Rosé Pine (月光玫瑰松)",
            Self::KanagawaWave => "Kanagawa Wave (浮世绘墨浪)",
            Self::Nord => "Nord (北欧极夜蓝灰)",
            Self::EverforestDark => "Everforest Dark (森雾暖暗绿)",
            Self::GruvboxDark => "Gruvbox Dark (复古胶片暖棕)",
            Self::Dracula => "Dracula (霓虹魅紫)",
            Self::MiyuForest => "Miyu Forest (MD3 鼠尾草暗色)",
            Self::CatppuccinLatte => "Catppuccin Latte (拿铁柔白)",
            Self::MiyuDay => "Miyu Day (冷调清浅)",
            Self::MiyuPaper => "Miyu Paper (暖调纸质浅色)",
            Self::Terminal => "Terminal (透明跟随终端)",
        }
    }

    /// 返回该内置主题的简短分类标记。
    pub fn category_tag(self) -> &'static str {
        match self {
            Self::Terminal => "透明",
            Self::CatppuccinLatte | Self::MiyuDay | Self::MiyuPaper => "浅色",
            _ => "深色",
        }
    }

    /// 判断内置主题是否属于深色基底（用于 MD3 自定义种子派生）。
    pub fn is_dark(self) -> bool {
        !matches!(self, Self::CatppuccinLatte | Self::MiyuDay | Self::MiyuPaper)
    }

    /// 解析内置主题 ID 或常见别名。
    ///
    /// 参数:
    /// - `s`: 主题 ID 或别名字符串（大小写不敏感）
    ///
    /// 返回:
    /// - 匹配成功返回 `Some(ThemePreset)`，否则返回 `None`
    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "miyu-lavender" | "lavender" | "miyu" => Some(Self::MiyuLavender),
            "miyu-night" | "night" | "tokyonight" | "tokyo-night" | "dark" => Some(Self::MiyuNight),
            "catppuccin-mocha" | "catppuccin" | "mocha" => Some(Self::CatppuccinMocha),
            "rose-pine" | "rosepine" | "rose" => Some(Self::RosePine),
            "kanagawa-wave" | "kanagawa" | "wave" => Some(Self::KanagawaWave),
            "nord" | "arctic" => Some(Self::Nord),
            "everforest-dark" | "everforest" => Some(Self::EverforestDark),
            "gruvbox-dark" | "gruvbox" => Some(Self::GruvboxDark),
            "dracula" => Some(Self::Dracula),
            "miyu-forest" | "forest" | "green" => Some(Self::MiyuForest),
            "catppuccin-latte" | "latte" => Some(Self::CatppuccinLatte),
            "miyu-day" | "day" | "light" => Some(Self::MiyuDay),
            "miyu-paper" | "paper" | "warm-light" | "cream" => Some(Self::MiyuPaper),
            "terminal" | "transparent" | "native" => Some(Self::Terminal),
            _ => None,
        }
    }

    /// 构建该内置主题的基础调色板（不含全局 `paint_bg` 覆写）。
    pub fn base_palette(self) -> Palette {
        match self {
            Self::MiyuLavender => md3_overlay(&NIGHT, 0x8b7cf6, true),
            Self::MiyuNight => NIGHT,
            Self::CatppuccinMocha => CATPPUCCIN_MOCHA,
            Self::RosePine => ROSE_PINE,
            Self::KanagawaWave => KANAGAWA_WAVE,
            Self::Nord => NORD,
            Self::EverforestDark => EVERFOREST_DARK,
            Self::GruvboxDark => GRUVBOX_DARK,
            Self::Dracula => DRACULA,
            Self::MiyuForest => md3_overlay(&NIGHT, 0x4ca87a, true),
            Self::CatppuccinLatte => CATPPUCCIN_LATTE,
            Self::MiyuDay => DAY,
            Self::MiyuPaper => PAPER,
            Self::Terminal => {
                let mut t = md3_overlay(&NIGHT, 0x8b7cf6, true);
                t.background = Color::Reset;
                t.surface = Color::Reset;
                t.panel_bg = Color::Reset;
                t.md_code_bg = Color::Reset;
                t
            }
        }
    }
}

